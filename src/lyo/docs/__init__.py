"""Documentation as a compilation step.

Nothing here runs as development proceeds; `lyo bundle` runs it. Each document
is generated from the code it describes -- the command list from click, the
declarations from the grammar, the settings from the installed adapters -- so a
brief cannot quietly drift from what the software does.

Staleness lives in the file itself, as a trailing stamp naming the version and
a hash of the inputs. A deleted state file does not lose that, and a document
copied out of the project still says what it was made from.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from lyo import __version__

GENERATORS = ("src/lyo/docs/__init__.py", "src/lyo/docs/pages.py")

STAMP = re.compile(r"<!-- generated by lyo (?P<version>[^\s]+) from (?P<hash>[0-9a-f]{16}) -->")


@dataclass
class Document:
    """One generated file, and the sources it is generated from."""

    path: str
    title: str
    render: Callable[[], str]
    inputs: tuple[str, ...] = ()

    def fingerprint(self, root: Path) -> str:
        #  The generators count as inputs to every document: editing the prose
        #  must make a document stale, not only editing what it describes.
        digest = hashlib.sha256(__version__.encode())
        for name in (*GENERATORS, *self.inputs):
            source = root / name
            digest.update(name.encode())
            digest.update(source.read_bytes() if source.exists() else b"")
        return digest.hexdigest()[:16]

    def stamp(self, root: Path) -> str:
        return f"<!-- generated by lyo {__version__} from {self.fingerprint(root)} -->"

    def current(self, root: Path) -> bool:
        """Whether the file on disk was made from today's inputs."""
        target = root / self.path
        if not target.exists():
            return False
        found = STAMP.search(target.read_text(encoding="utf-8"))
        return bool(found and found["hash"] == self.fingerprint(root))

    def write(self, root: Path) -> Path:
        target = root / self.path
        target.parent.mkdir(parents=True, exist_ok=True)
        #  newline="": a document generated on Windows is the same bytes as
        #  one generated here, so its hash does not depend on the host.
        target.write_text(f"{self.render().rstrip()}\n\n{self.stamp(root)}\n",
                          encoding="utf-8", newline="")
        return target


def terms(rows: list[tuple[str, str]]) -> str:
    """The mini table of terms every brief carries."""
    width = max(len(t) for t, _ in rows)
    lines = [f"| {'Term'.ljust(width)} | Definition |",
             f"| {'-' * width} | ---------- |"]
    lines += [f"| {term.ljust(width)} | {meaning} |" for term, meaning in rows]
    return "\n".join(lines)


# ----------------------------------------------------------- introspection


def commands() -> list[tuple[str, str, str]]:
    """Every CLI command, from click itself: name, arguments, one-line help."""
    from lyo.cli import main

    found = []
    for name, command in sorted(main.commands.items()):
        if hasattr(command, "commands"):  # a group, such as `service`
            for sub, child in sorted(command.commands.items()):
                found.append((f"{name} {sub}", _usage(child),
                              (child.help or "").strip().split("\n")[0]))
            continue
        found.append((name, _usage(command),
                      (command.help or "").strip().split("\n")[0]))
    return found


def _usage(command) -> str:
    import click

    parts = []
    for parameter in command.params:
        if isinstance(parameter, click.Argument):
            label = parameter.name.upper()
            if parameter.required:
                parts.append(f"<{label}>")
            elif parameter.nargs == -1:
                parts.append(f"[{label}...]")
            else:
                parts.append(f"[{label}]")
    return " ".join(parts)


def declarations() -> list[str]:
    """The top-level declarations, read out of the grammar.

    `npc` is a declaration too, but only inside a `location`, so it is not
    listed here.
    """
    from lyo.lang.parser import grammar_text

    names = re.findall(r"^(\w+)_decl:", grammar_text(), re.MULTILINE)
    #  `start` lists them in the order the language presents them.
    order = re.search(r"declaration: (.+?)\n\n", grammar_text(), re.DOTALL)
    if order:
        listed = re.findall(r"(\w+)_decl", order.group(1))
        names = [n for n in listed if n in names]
    return names


def statements() -> list[str]:
    from lyo.engine.execute import _STATEMENTS

    return sorted(k for k in _STATEMENTS if not k.endswith("_stmt"))


def adapters() -> dict:
    from lyo import plugins

    return plugins.adapters()


def tables() -> list[str]:
    from importlib.resources import files

    schema = (files("lyo.store") / "schema.sql").read_text(encoding="utf-8")
    return re.findall(r"CREATE TABLE IF NOT EXISTS (\w+)", schema)
